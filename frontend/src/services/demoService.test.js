import { beforeEach, describe, expect, it } from 'vitest'
import {
  analyzeDemoDocument,
  checkDemoSchemeEligibility,
  downloadDemoApplicationPdf,
  generateDemoForm,
  getDemoDashboard,
  getDemoDocuments,
  getDemoProfile,
  getDemoSchemeAnswers,
  sendDemoLegalQuestion,
  uploadDemoDocument,
  validateDemoForm,
} from './demoService'
import { enterDemoSession, resetDemoData } from './demoStore'

function createStorage() {
  const values = new Map()
  return {
    getItem: (key) => values.get(key) ?? null,
    setItem: (key, value) => values.set(key, String(value)),
    removeItem: (key) => values.delete(key),
    clear: () => values.clear(),
  }
}

beforeEach(() => {
  globalThis.localStorage = createStorage()
  enterDemoSession()
})

describe('demo workspace', () => {
  it('persists edited profile data and keeps dashboard records explicitly marked as demo', async () => {
    const dashboard = (await getDemoDashboard()).data
    expect(dashboard.demo_mode).toBe(true)
    expect(dashboard.applications.length).toBeGreaterThan(0)

    const { updateDemoProfile } = await import('./demoService')
    await updateDemoProfile({ phone: '+91 11111 11111' })
    expect((await getDemoProfile()).data.phone).toBe('+91 11111 11111')
  })

  it('returns missing information instead of claiming official scheme eligibility', async () => {
    const result = (await checkDemoSchemeEligibility('demo-pmjay', {})).data
    expect(result.status).toBe('needs_information')
    expect(result.is_eligible).toBeNull()
    expect(result.demo_simulated).toBe(true)
    expect(result.missing_information.length).toBeGreaterThan(0)
    await checkDemoSchemeEligibility('demo-pmjay', { listed_in_pmjay: 'yes' })
    expect((await getDemoSchemeAnswers('demo-pmjay')).data.listed_in_pmjay).toBe('yes')
  })

  it('validates required fields and generates a downloadable demo draft PDF', async () => {
    const incomplete = validateDemoForm({ template_id: 'general_support', data: {} })
    expect(incomplete.valid).toBe(false)
    expect(incomplete.missing_fields).toContain('full_name')

    const payload = {
      template_id: 'general_support',
      data: { full_name: 'Demo Citizen', phone: '1234567890', address: 'Example Street', request_summary: 'Sample request' },
    }
    const application = (await generateDemoForm(payload)).data
    expect(application.is_demo).toBe(true)
    const pdf = await downloadDemoApplicationPdf(application.id)
    expect(pdf.data.type).toBe('application/pdf')
    expect(pdf.data.size).toBeGreaterThan(100)
    expect(await pdf.data.text()).toContain('DEMONSTRATION DOCUMENT')
  })

  it('rejects invalid file signatures and only creates scripted extraction results', async () => {
    const invalidFile = {
      name: 'sample.pdf',
      type: 'application/pdf',
      size: 5,
      slice: () => new Blob(['NOPE!']),
    }
    await expect(uploadDemoDocument(invalidFile)).rejects.toThrow(/signature/)
    await expect(uploadDemoDocument({ ...invalidFile, size: 10 * 1024 * 1024 + 1 }))
      .rejects.toThrow(/no larger than 10 MiB/)

    const validFile = {
      name: 'sample-income.pdf',
      type: 'application/pdf',
      size: 5,
      slice: () => new Blob([new Uint8Array([0x25, 0x50, 0x44, 0x46, 0x2d])]),
    }
    const { data: uploaded } = await uploadDemoDocument(validFile)
    const extraction = (await analyzeDemoDocument(uploaded.id)).data
    expect(extraction.demo_simulated).toBe(true)
    expect(extraction.processing_method).toMatch(/no OCR/i)
    expect((await getDemoDocuments()).data.find((item) => item.id === uploaded.id).extraction).toEqual(extraction)
  })

  it('stores scripted legal conversations and identifies them as non-Gemini demo replies', async () => {
    const result = (await sendDemoLegalQuestion({ message: 'Where can I submit an RTI request?', category: 'rti' })).data
    expect(result.demo_simulated).toBe(true)
    expect(result.grounded).toBe(false)
    expect(result.sources[0].url).toBe('https://rtionline.gov.in/')
    expect(result.disclaimer).toMatch(/not generated by Gemini/i)
    expect(() => sendDemoLegalQuestion({ message: 'x'.repeat(2001) })).toThrow(/2000 characters or fewer/)
  })

  it('restores the seeded workspace without requiring an API session', async () => {
    await generateDemoForm({
      template_id: 'general_support',
      data: { full_name: 'Demo Citizen', phone: '1234567890', address: 'Example Street', request_summary: 'Sample request' },
    })
    resetDemoData()
    expect((await getDemoDashboard()).data.applications).toHaveLength(2)
  })
})
